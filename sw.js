/*
 TestTrack Service Worker v4
*/
const CACHE_NAME = "testtrack-v4";
const FILES = [
"./",
"./index.html",
"./app.js",
"./geo.js",
"./media.js",
"./manifest.json",
"./icon-192.png",
"./icon-512.png",
"./icon-180.png",
"./icon-32.png",
"./icon-16.png",
"./favicon.ico"
];
self.addEventListener(
"install",
event=>{
event.waitUntil(
caches.open(CACHE_NAME)
.then(
cache=>cache.addAll(FILES)
)
);
});
self.addEventListener(
"activate",
event=>{
event.waitUntil(
caches.keys()
.then(
keys=>
Promise.all(
keys
.filter(
key=>key!==CACHE_NAME
)
.map(
key=>caches.delete(key)
)
)
)
);
});
self.addEventListener(
"fetch",
event=>{
event.respondWith(
caches.match(event.request)
.then(
response=>{
return response || fetch(event.request);
}
)
);
});
